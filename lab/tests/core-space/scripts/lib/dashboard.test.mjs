test("renderDashboard is self-contained, with generation time and all sections", () => {
  const html = renderDashboard({
    generatedAt: '2026-09-11 23:10:00',
    sections: [
      { title: "Latest Daily Report", items: ['<script>alert(1)</script>'] },
      { title: "Long-Term Memory", items: ["\u51b3\u7b56：\u5355\u4e00\u771f\u6e90"] },
    ],
  });
  assert.match(html, /<!doctype html>/i);
  assert.match(html, /Dashboard generated at 2026-09-11 23:10:00/);
  assert.match(html, /Latest Daily Report/);
  assert.match(html, /Long-Term Memory/);
  assert.ok(!/https?:\/\//.test(html), "No external links are permitted");
  assert.ok(!/<script src=/.test(html), "Do not load external scripts");
  assert.ok(html.includes('&lt;script&gt;'), "Escape all content");
  assert.ok(html.includes('<style>'), "CSS must be inline");
  assert.ok(!/src=/.test(html), "No external scripts; inline scripts are allowed");
  assert.match(html, /Date\.now\(\)/, "Compute freshness when opened through an inline script");
  assert.match(html, /data-at="2026-09-11 23:10:00"/, "Include the data timestamp for age calculation when opened");
  assert.match(html, /Snapshot time/, "Show the snapshot age immediately so stale data is not mistaken for live values");
  assert.match(html, /class="chips"/, "Include a summary-chip container generated by groups");
});

